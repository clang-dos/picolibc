#include "local-msdos.h"
#include <time.h>

/* DOS has no sleep call; wait on the clock. */
int
nanosleep(const struct timespec *req, struct timespec *rem)
{
    if (req->tv_nsec < 0 || req->tv_nsec >= 1000000000L || req->tv_sec < 0) {
        errno = EINVAL;
        return -1;
    }
    int64_t s;
    uint16_t c;
    __msdos_time(&s, &c);
    int64_t end = s * 100 + c + req->tv_sec * 100 + (req->tv_nsec + 9999999L) / 10000000L;
    int64_t now;
    do {
        __msdos_time(&s, &c);
        now = s * 100 + c;
    } while (now < end);
    if (rem) {
        rem->tv_sec = 0;
        rem->tv_nsec = 0;
    }
    return 0;
}
