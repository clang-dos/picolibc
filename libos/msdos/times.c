#include "local-msdos.h"
#include <sys/times.h>
#include <time.h>

/* Process time is the time since the program started, in units of
 * CLOCKS_PER_SEC, which is also what clock() returns. */
clock_t
times(struct tms *buf)
{
    int64_t s;
    uint16_t c;
    __msdos_time(&s, &c);
    int64_t now = s * 100 + c;
    if (now < __msdos_start_centi)
        now += 8640000; /* the clock passed midnight */
    clock_t t = (clock_t)(now - __msdos_start_centi) * (CLOCKS_PER_SEC / 100);
    if (buf) {
        buf->tms_utime = t;
        buf->tms_stime = 0;
        buf->tms_cutime = 0;
        buf->tms_cstime = 0;
    }
    return t;
}
